func TestTransformFunc_RenamesTypesAndIdentifiers(t *testing.T) {
	src := `// forwardDIT8Radix2Complex64 computes an 8-point forward FFT for complex64 data.
func forwardDIT8Radix2Complex64(dst, src, twiddle, scratch []complex64) bool {
	const n = 8
	var t complex64
	_ = t
	return ditForward[complex64](dst, src, twiddle, scratch)
}`

	got := transformFunc(src, nil)

	want := `// forwardDIT8Radix2Complex128 computes an 8-point forward FFT for complex128 data.
func forwardDIT8Radix2Complex128(dst, src, twiddle, scratch []complex128) bool {
	const n = 8
	var t complex128
	_ = t
	return ditForward[complex128](dst, src, twiddle, scratch)
}`
	if got != want {
		t.Errorf("transformFunc mismatch:\ngot:\n%s\nwant:\n%s", got, want)
	}
}

func TestTransformFunc_InverseScaling(t *testing.T) {
	cases := []struct {
		name, in, want string
	}{
		{
			name: "float32 over float64 n",
			in:   `scale := complex(float32(1.0/float64(n)), 0)`,
			want: `scale := complex(1.0/float64(n), 0)`,
		},
		{
			name: "float32 one over float32 n",
			in:   `scale := complex(float32(1)/float32(n), 0)`,
			want: `scale := complex(1/float64(n), 0)`,
		},
		{
			name: "float32 literal ratio",
			in:   `const scale = float32(1.0 / 1024.0)`,
			want: `const scale = 1.0 / 1024.0`,
		},
		{
			name: "float32 literal constant",
			in:   `sin1 = float32(0.382683432365089771728459984030398866761)`,
			want: `sin1 = 0.382683432365089771728459984030398866761`,
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := transformFunc(tc.in, nil)
			if got != tc.want {
				t.Errorf("got %q, want %q", got, tc.want)
			}
		})
	}
}

func TestTransformFunc_RenamesPairedPackageIdents(t *testing.T) {
	renames := map[string]string{"radix3Half64": "radix3Half128"}

	got := transformFunc(`h := radix3Half64 * radix3Half64x`, renames)

	// radix3Half64x must not be touched: whole-identifier match only.
	want := `h := radix3Half128 * radix3Half64x`
	if got != want {
		t.Errorf("got %q, want %q", got, want)
	}
}

func TestGenerateFile_EmitsHeaderPackageAndImports(t *testing.T) {
	src := `package kernels

import (
	stdmath "math"

	mathpkg "github.com/cwbudde/algo-fft/internal/math"
)

var shared = mathpkg.ComputeBitReversalIndices(16)

// forwardTinyComplex64 is a twin source.
func forwardTinyComplex64(dst, src []complex64) bool {
	_ = stdmath.Sqrt(2)
	_ = shared
	return true
}

// keepMe is not a twin source.
func keepMe() {}

// skippedComplex64 is excluded by name.
func skippedComplex64() {}
`

	out, err := generateFile("tiny.go", []byte(src), map[string]bool{"skippedComplex64": true})
	if err != nil {
		t.Fatalf("generateFile: %v", err)
	}

	text := string(out)

	if !strings.HasPrefix(text, "// Code generated by genkernels from tiny.go. DO NOT EDIT.") {
		t.Errorf("missing generated header:\n%s", text)
	}

	if !strings.Contains(text, "func forwardTinyComplex128(dst, src []complex128) bool {") {
		t.Errorf("missing transformed twin:\n%s", text)
	}

	// The twin uses stdmath, so that import must be carried over; mathpkg is
	// only used by the package-level var and must not appear.
	if !strings.Contains(text, `stdmath "math"`) {
		t.Errorf("missing stdmath import:\n%s", text)
	}

	if strings.Contains(text, "mathpkg") {
		t.Errorf("unexpected mathpkg import:\n%s", text)
	}

	if strings.Contains(text, "keepMe") || strings.Contains(text, "skippedComplex128") {
		t.Errorf("non-twin or excluded function leaked into output:\n%s", text)
	}
}

func TestGenerateFile_NoTwinSourcesReturnsNil(t *testing.T) {
	out, err := generateFile("x.go", []byte("package kernels\n\nfunc plain() {}\n"), nil)
	if err != nil {
		t.Fatalf("generateFile: %v", err)
	}

	if out != nil {
		t.Errorf("expected nil output for file without Complex64 functions, got:\n%s", out)
	}
}
