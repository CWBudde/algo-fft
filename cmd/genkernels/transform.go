package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"regexp"
	"strings"
)

// The complex64 sources use float32 conversions that have no complex128
// counterpart: the twin uses the untyped expression directly (matching what
// the hand-written complex128 kernels did). Ordered: the 1/n forms must run
// before the bare-literal rule, which would otherwise consume `float32(1)`.
//
//nolint:gochecknoglobals // static rewrite rules for the generator
var float32Rules = []struct {
	re          *regexp.Regexp
	replacement string
}{
	// float32(1)/float32(n) -> 1/float64(n)
	{regexp.MustCompile(`float32\(1\)\s*/\s*float32\(n\)`), "1/float64(n)"},
	// float32(1.0/float32(n)) -> 1.0/float64(n). The inner conversion has to go
	// too, or the twin would narrow to float32 and then fail to multiply a
	// float64 component.
	{regexp.MustCompile(`float32\((1(?:\.0)?)\s*/\s*float32\(n\)\)`), "$1/float64(n)"},
	// float32(1.0/float64(n)) -> 1.0/float64(n). gofmt spaces the operator when
	// this appears at statement level (`scale := float32(1.0 / float64(n))`) but
	// not inside a call argument, so both spacings have to match.
	{regexp.MustCompile(`float32\((1(?:\.0)?\s*/\s*float64\(n\))\)`), "$1"},
	// float32(1.0 / 1024.0) -> 1.0 / 1024.0
	{regexp.MustCompile(`float32\((1(\.0)?\s*/\s*[0-9]+(\.[0-9]+)?)\)`), "$1"},
	// float32(0.38268…) -> 0.38268…
	{regexp.MustCompile(`float32\(([0-9]+(\.[0-9]+)?([eE][+-]?[0-9]+)?)\)`), "$1"},
}

// transformFunc rewrites the source text of one Complex64 function (including
// its doc comment) into its Complex128 twin. renames maps package-level
// identifiers to their 128-suffixed siblings (e.g. radix3Half64 ->
// radix3Half128); function-local names never need it.
func transformFunc(src string, renames map[string]string) string {
	src = strings.ReplaceAll(src, "Complex64", "Complex128")
	src = strings.ReplaceAll(src, "complex64", "complex128")

	for _, rule := range float32Rules {
		src = rule.re.ReplaceAllString(src, rule.replacement)
	}

	for from, to := range renames {
		src = regexp.MustCompile(`\b`+regexp.QuoteMeta(from)+`\b`).ReplaceAllString(src, to)
	}

	return src
}

// generateFile produces the generated-twin file contents for one kernels
// source file, or nil if the file contains no eligible Complex64 functions.
func generateFile(filename string, src []byte, excluded map[string]bool) ([]byte, error) {
	fset := token.NewFileSet()

	f, err := parser.ParseFile(fset, filename, src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", filename, err)
	}

	renames := pairedIdentRenames(f)

	var twins []string

	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || !strings.Contains(fd.Name.Name, "Complex64") || excluded[fd.Name.Name] {
			continue
		}

		start := fd.Pos()
		if fd.Doc != nil {
			start = fd.Doc.Pos()
		}

		text := string(src[fset.Position(start).Offset:fset.Position(fd.End()).Offset])
		twins = append(twins, transformFunc(text, renames))
	}

	if len(twins) == 0 {
		return nil, nil
	}

	body := strings.Join(twins, "\n\n")

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genkernels from %s. DO NOT EDIT.\n\n", filename)
	b.WriteString("package kernels\n\n")

	if imports := usedImports(f, body); imports != "" {
		b.WriteString(imports)
		b.WriteString("\n\n")
	}

	b.WriteString(body)
	b.WriteString("\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated twin of %s: %w\n%s", filename, err, b.Bytes())
	}

	return out, nil
}

// pairedIdentRenames returns the 64->128 renames for package-level
// identifiers that exist in both suffixes in this file (e.g. radix3Half64 /
// radix3Half128). Identifiers merely containing "64" (bitrev64Radix2) are
// left alone.
func pairedIdentRenames(f *ast.File) map[string]string {
	names := map[string]bool{}

	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}

		for _, spec := range gd.Specs {
			if vs, ok := spec.(*ast.ValueSpec); ok {
				for _, id := range vs.Names {
					names[id.Name] = true
				}
			}
		}
	}

	renames := map[string]string{}

	for name := range names {
		if !strings.HasSuffix(name, "64") {
			continue
		}

		sibling := strings.TrimSuffix(name, "64") + "128"
		if names[sibling] {
			renames[name] = sibling
		}
	}

	return renames
}

// usedImports renders the subset of the source file's imports whose qualifier
// appears in the generated body, or "" if none do.
func usedImports(f *ast.File, body string) string {
	var kept []string

	for _, imp := range f.Imports {
		path := strings.Trim(imp.Path.Value, `"`)

		qualifier := path[strings.LastIndex(path, "/")+1:]
		if imp.Name != nil {
			qualifier = imp.Name.Name
		}

		if regexp.MustCompile(`\b` + regexp.QuoteMeta(qualifier) + `\.`).MatchString(body) {
			if imp.Name != nil {
				kept = append(kept, fmt.Sprintf("%s %q", imp.Name.Name, path))
			} else {
				kept = append(kept, fmt.Sprintf("%q", path))
			}
		}
	}

	if len(kept) == 0 {
		return ""
	}

	return "import (\n\t" + strings.Join(kept, "\n\t") + "\n)"
}
