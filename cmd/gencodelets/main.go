// Command gencodelets generates the built-in codelet registration functions in
// internal/kernels from the declarative table in specs.go.
//
// It emits one file per build target (generic / avx2 / sse2 / neon), each
// containing register{Kind}DITCodelets64 and register{Kind}DITCodelets128
// functions that populate the global codelet registries (internal/registry)
// at init time. The hand-written init scaffolding lives in
// internal/kernels/codelet_registry.go.
//
// With -inventory <path>, it instead renders the implementation inventory
// document (docs/IMPLEMENTATION_INVENTORY.md) from the same table.
//
// Regenerate with: go generate ./internal/kernels/...
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// target describes one output file and its build constraints.
type target struct {
	kind      string // spec.Target value
	file      string // output filename (relative to the kernels package dir)
	buildTag  string // //go:build constraint, empty for the generic target
	regPrefix string // register function infix: "" | "AVX2" | "SSE2" | "NEON"
	importPkg string // qualified import path, empty if none
	importAs  string // import alias / detection prefix, e.g. "amd64"
}

//nolint:gochecknoglobals // static configuration table for the generator
var targets = []target{
	{kind: "generic", file: "codelet_init_generic.gen.go", buildTag: "", regPrefix: "", importPkg: "", importAs: ""},
	{kind: "avx2", file: "codelet_init_avx2.gen.go", buildTag: "amd64 && !purego", regPrefix: "AVX2", importPkg: "github.com/cwbudde/algo-fft/internal/asm/amd64", importAs: "amd64"},
	{kind: "avx512", file: "codelet_init_avx512.gen.go", buildTag: "amd64 && !purego", regPrefix: "AVX512", importPkg: "github.com/cwbudde/algo-fft/internal/asm/amd64", importAs: "amd64"},
	{kind: "sse2", file: "codelet_init_sse2.gen.go", buildTag: "amd64 && !purego", regPrefix: "SSE2", importPkg: "github.com/cwbudde/algo-fft/internal/asm/amd64", importAs: "amd64"},
	{kind: "neon", file: "codelet_init_neon.gen.go", buildTag: "arm64 && !purego", regPrefix: "NEON", importPkg: "github.com/cwbudde/algo-fft/internal/asm/arm64", importAs: "arm64"},
}

func main() {
	inventoryPath := flag.String("inventory", "",
		"render the implementation inventory markdown to this path instead of generating code")
	flag.Parse()

	if *inventoryPath != "" {
		// The census reads the tree, not the spec table, so it needs the
		// module root; go:generate runs this from internal/kernels.
		root, err := findModuleRoot(".")
		if err != nil {
			fmt.Fprintf(os.Stderr, "gencodelets: %v\n", err)
			os.Exit(1)
		}

		c, err := runCensus(root)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gencodelets: census: %v\n", err)
			os.Exit(1)
		}

		probes, err := scanProbeFiles(root)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gencodelets: probes: %v\n", err)
			os.Exit(1)
		}

		err = os.WriteFile(*inventoryPath, renderInventory(c, probes, root), 0o644) //nolint:gosec
		if err != nil {
			fmt.Fprintf(os.Stderr, "gencodelets: write %s: %v\n", *inventoryPath, err)
			os.Exit(1)
		}

		fmt.Fprintf(os.Stderr, "gencodelets: wrote %s\n", *inventoryPath)

		return
	}

	outDir := "internal/kernels"
	if flag.NArg() > 0 {
		outDir = flag.Arg(0)
	}

	for _, tgt := range targets {
		src := renderTarget(tgt)

		formatted, err := format.Source(src)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gencodelets: format %s: %v\n---\n%s\n", tgt.file, err, src)
			os.Exit(1)
		}

		path := filepath.Join(outDir, tgt.file)

		err = os.WriteFile(path, formatted, 0o644) //nolint:gosec
		if err != nil {
			fmt.Fprintf(os.Stderr, "gencodelets: write %s: %v\n", path, err)
			os.Exit(1)
		}

		fmt.Fprintf(os.Stderr, "gencodelets: wrote %s\n", path)
	}
}

func renderTarget(tgt target) []byte {
	var b bytes.Buffer

	b.WriteString("// Code generated by cmd/gencodelets; DO NOT EDIT.\n")
	b.WriteString("// Source of truth: cmd/gencodelets/specs.go\n\n")

	if tgt.buildTag != "" {
		fmt.Fprintf(&b, "//go:build %s\n\n", tgt.buildTag)
	}

	b.WriteString("package kernels\n\n")

	// Registration goes straight to the leaf registry package; the strategy/
	// SIMD/kernel-type constants live in fftypes. The optional per-arch asm
	// import is emitted only when the target actually references it.
	b.WriteString("import (\n")
	b.WriteString("\"github.com/cwbudde/algo-fft/internal/fftypes\"\n")
	b.WriteString("\"github.com/cwbudde/algo-fft/internal/registry\"\n")

	if tgt.importPkg != "" && targetUsesImport(tgt) {
		fmt.Fprintf(&b, "%s %q\n", tgt.importAs, tgt.importPkg)
	}

	b.WriteString(")\n\n")

	for _, prec := range []int{64, 128} {
		renderRegisterFunc(&b, tgt, prec)
	}

	return b.Bytes()
}

func renderRegisterFunc(b *bytes.Buffer, tgt target, prec int) {
	fnName := fmt.Sprintf("register%sDITCodelets%d", tgt.regPrefix, prec)

	kind := "generic"
	if tgt.regPrefix != "" {
		kind = tgt.regPrefix
	}

	fmt.Fprintf(b, "// %s registers the %s complex%d DIT codelets.\n", fnName, kind, prec)
	fmt.Fprintf(b, "func %s() {\n", fnName)

	for i, s := range specsFor(tgt.kind, prec) {
		if i > 0 {
			b.WriteString("\n")
		}

		renderRegister(b, s)
	}

	b.WriteString("}\n\n")
}

func renderRegister(b *bytes.Buffer, s codeletSpec) {
	reg := fmt.Sprintf("registry.Registry%d", s.Prec)

	fmt.Fprintf(b, "%s.Register(registry.CodeletEntry[complex%d]{\n", reg, s.Prec)
	fmt.Fprintf(b, "Size: %d,\n", s.Size)
	fmt.Fprintf(b, "Forward: %s,\n", s.Forward)
	fmt.Fprintf(b, "Inverse: %s,\n", s.Inverse)
	fmt.Fprintf(b, "Algorithm: fftypes.%s,\n", s.Algorithm)
	fmt.Fprintf(b, "SIMDLevel: fftypes.%s,\n", s.SIMDLevel)
	fmt.Fprintf(b, "Signature: %q,\n", s.Signature)
	fmt.Fprintf(b, "Priority: %d,\n", s.Priority)
	fmt.Fprintf(b, "KernelType: fftypes.%s,\n", s.KernelType)

	if s.RankLevel != "" {
		fmt.Fprintf(b, "RankLevel: fftypes.%s,\n", s.RankLevel)
	}

	if s.RankBelowGeneric {
		b.WriteString("RankBelowGeneric: true,\n")
	}

	if s.TwiddleSize != "" {
		fmt.Fprintf(b, "TwiddleSize: %s,\n", s.TwiddleSize)
	}

	if s.PrepareTwiddle != "" {
		fmt.Fprintf(b, "PrepareTwiddle: %s,\n", s.PrepareTwiddle)
	}

	b.WriteString("})\n")
}

// specsFor returns the specs for a target kind and precision, preserving table order.
func specsFor(kind string, prec int) []codeletSpec {
	var out []codeletSpec

	for _, s := range codeletSpecs {
		if s.Target == kind && s.Prec == prec {
			out = append(out, s)
		}
	}

	return out
}

// targetUsesImport reports whether any spec for this target references the import prefix.
func targetUsesImport(tgt target) bool {
	prefix := tgt.importAs + "."

	for _, s := range codeletSpecs {
		if s.Target != tgt.kind {
			continue
		}

		if strings.HasPrefix(s.Forward, prefix) || strings.HasPrefix(s.Inverse, prefix) {
			return true
		}
	}

	return false
}
