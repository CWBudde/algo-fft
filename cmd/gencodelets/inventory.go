var signatureRe = regexp.MustCompile(`^dit[0-9]+_(.+)_(generic|avx2|avx512|sse2|sse3|neon)$`)

// variantOf derives the display variant from a codelet signature.
func variantOf(sig string) string {
	m := signatureRe.FindStringSubmatch(sig)
	if m == nil {
		return sig
	}

	if name, ok := variantNames[m[1]]; ok {
		return name
	}

	return m[1]
}

type gridKey struct {
	size    int
	variant string
}

func renderInventory(c *census, probes []probeEntry) []byte {
	var b bytes.Buffer

	b.WriteString("# FFT Implementation Inventory\n\n")
	b.WriteString("<!-- Code generated by cmd/gencodelets from cmd/gencodelets/specs.go; DO NOT EDIT.\n")
	b.WriteString("     Regenerate with: go generate ./internal/kernels/... -->\n\n")
	b.WriteString("This document inventories the size-specific FFT codelets registered by\n")
	b.WriteString("`internal/kernels` (source of truth: the declarative table in\n")
	b.WriteString("`cmd/gencodelets/specs.go`), censuses every assembly symbol under\n")
	b.WriteString("`internal/asm` for reachability, and summarizes the non-codelet kernel tiers.\n")
	b.WriteString("SIMD kernels are part of the **default build** and are selected at runtime\n")
	b.WriteString("via `internal/cpu.DetectFeatures()`; build with `-tags purego` for the\n")
	b.WriteString("pure-Go fallback.\n\n")

	for _, prec := range []int{64, 128} {
		fmt.Fprintf(&b, "## Codelet Quick Reference — complex%d\n\n", prec)
		renderGrid(&b, prec)
	}

	renderCounts(&b)
	renderCensus(&b, c)
	renderProbes(&b, probes)
	renderStaticSections(&b)

	return b.Bytes()
}

// renderCensus writes the assembly symbol census: one row per .s file per
// architecture, plus the actionable lists (symbols nothing reaches, and data
// symbols shared across files).
func renderCensus(b *bytes.Buffer, c *census) {
	if c == nil {
		return
	}

	b.WriteString(strings.TrimLeft(`
## Assembly Symbol Census

Every `+"`TEXT`"+` symbol under internal/asm, with the bodyless Go declaration
that binds it and whether anything in a production build reaches it. The
reference graph is matched by identifier name across all build tags and
ignores shadowing, so it **over-approximates reachability**: a symbol listed
as reachable may still be dead, but one listed unreachable is referenced by no
live non-test code.

Reachability is computed from these roots: every exported func and method of
the root package `+"`algofft`"+`, every `+"`init`"+`, every package-level var/const
initializer, and every func under cmd/. A verdict is only as good as that
list — if a genuine entry point is missing from it, whole subtrees read as
unreachable.

- **live** — reachable from the root package's exported API, an `+"`init`"+`, or a
  package-level initializer.
- **unreachable** — referenced only from non-test Go code that is itself
  unreachable (the second-order case: a live-looking thunk with no live caller).
- **test-only** — referenced only from `+"`_test.go`"+` files. Declared-but-uncalled
  assembly is untested assembly; these run only when a test names them.
- **orphan** — declared and referenced by nothing at all.

`, "\n"))

	for _, group := range c.Groups {
		renderCensusGroup(b, c, group)
	}

	renderCensusUnreached(b, c)
	renderCensusShared(b, c)
}

// renderProbes writes the probe-gated kernel section: every `-tags fftprobe`
// file in the tree, with the verdict of the sweep that produced it and the
// command that takes the number again.
func renderProbes(b *bytes.Buffer, probes []probeEntry) {
	b.WriteString(strings.TrimLeft(`
## Probe-Gated Kernels

Anything behind `+"`-tags fftprobe`"+` is in the tree but outside every production
build and every registry lookup, so it costs nothing at runtime. A kernel is
kept this way when it lost a measurement rather than a structural argument
(PLAN.md §2.2): deleting the file is what would make the second measurement
impossible, and an unlisted probe is a question on its way back to folklore.

The file list is scanned from the build constraints; the verdicts are authored
in `+"`cmd/gencodelets/probes.go`"+`, and a probe file with no verdict fails the
generator's tests.

`, "\n"))

	if len(probes) == 0 {
		b.WriteString("None: no file in the tree carries the `fftprobe` constraint.\n\n")

		return
	}

	b.WriteString("| File | Build tag | Measures | Status |\n")
	b.WriteString("|---|---|---|---|\n")

	for _, p := range probes {
		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s |\n",
			p.Path, p.Constraint, p.Note.Subject, p.Note.Status)
	}

	b.WriteString("\n")

	for _, p := range probes {
		fmt.Fprintf(b, "**`%s`** — %s\n\n", p.Path, p.Note.Status)

		if p.Note.Verdict != "" {
			fmt.Fprintf(b, "%s\n\n", p.Note.Verdict)
		}

		if p.Note.Record != "" {
			fmt.Fprintf(b, "- Recorded in: %s\n", p.Note.Record)
		}

		if p.Note.Rederiv != "" {
			fmt.Fprintf(b, "- Re-derive: `PATH=/usr/local/go/bin:$PATH %s`\n", p.Note.Rederiv)
		}

		b.WriteString("\n")
	}
}

// renderCensusGroup writes the per-file table for one architecture directory.
func renderCensusGroup(b *bytes.Buffer, c *census, group string) {
	files := 0
	syms := 0
	live := 0

	for _, f := range c.Files {
		if f.Group == group {
			files++
			syms += len(f.Symbols)
			live += f.Live()
		}
	}

	fmt.Fprintf(b, "### %s — %d files, %d symbols, %d live\n\n", group, files, syms, live)
	b.WriteString("| File | Symbols | Live | Test-only | Unreachable | Orphan | Declared in |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---|\n")

	for _, f := range c.Files {
		if f.Group != group {
			continue
		}

		decls := "—"
		if len(f.DeclFiles) > 0 {
			decls = "`" + strings.Join(f.DeclFiles, "`, `") + "`"
		}

		fmt.Fprintf(b, "| `%s` | %d | %d | %d | %d | %d | %s |\n",
			strings.TrimPrefix(f.Path, "internal/asm/"),
			len(f.Symbols), f.Live(), f.count(symTestOnly),
			f.count(symUnreachable), f.count(symOrphan), decls)
	}

	b.WriteString("\n")
}

// renderCensusUnreached lists the files no production build reaches at all —
// the deletion / probe-gating candidates — and then every individual symbol
// that is not live.
func renderCensusUnreached(b *bytes.Buffer, c *census) {
	b.WriteString("### Files with no live symbol\n\n")

	dead := 0

	for _, f := range c.Files {
		if len(f.Symbols) == 0 || f.Live() > 0 {
			continue
		}

		dead++

		fmt.Fprintf(b, "- `%s` — %d symbols, none reachable\n", f.Path, len(f.Symbols))
	}

	if dead == 0 {
		b.WriteString("None: every .s file has at least one reachable symbol.\n")
	}

	b.WriteString("\nDo not delete on this list alone — check the shared data symbols below,\n")
	b.WriteString("and see PLAN.md §2.2 for when an unreachable kernel should be probe-gated\n")
	b.WriteString("(`-tags fftprobe`) rather than removed.\n\n")

	b.WriteString("### Symbols not reachable from a production build\n\n")
	b.WriteString("| Symbol | Status | Defined in | Declared in |\n")
	b.WriteString("|---|---|---|---|\n")

	for _, f := range c.Files {
		for _, s := range f.Symbols {
			if s.Status == symLive {
				continue
			}

			decl := "—"
			if s.DeclFile != "" {
				decl = "`" + s.DeclFile + "`"
			}

			fmt.Fprintf(b, "| `%s` | %s | `%s` | %s |\n",
				s.Name, s.Status, strings.TrimPrefix(s.File, "internal/asm/"), decl)
		}
	}

	b.WriteString("\n")
}

// renderCensusShared lists package-visible GLOBL data symbols used from a file
// other than the one defining them. Deleting a defining file breaks the build;
// this has happened once.
func renderCensusShared(b *bytes.Buffer, c *census) {
	b.WriteString("### Data symbols shared across files\n\n")

	if len(c.Shared) == 0 {
		b.WriteString("None.\n\n")

		return
	}

	b.WriteString("Relocate these into a shared table file before deleting the file that\n")
	b.WriteString("defines them (internal/asm/amd64/bitrev_radix4_tables.s is the\n")
	b.WriteString("established home).\n\n")
	b.WriteString("| Data symbol | Defined in | Used from |\n")
	b.WriteString("|---|---|---|\n")

	// A widely-shared constant (the 1/n scale factors) would otherwise make
	// this table hundreds of columns wide, so the list is capped.
	const maxUsers = 3

	for _, s := range c.Shared {
		users := make([]string, 0, len(s.UsedFrom))
		for _, u := range s.UsedFrom {
			users = append(users, "`"+strings.TrimPrefix(u, "internal/asm/")+"`")
		}

		more := ""
		if len(users) > maxUsers {
			more = fmt.Sprintf(" + %d more", len(users)-maxUsers)
			users = users[:maxUsers]
		}

		fmt.Fprintf(b, "| `%s` | `%s` | %s%s |\n",
			s.Name,
			strings.TrimPrefix(s.DefFile, "internal/asm/"),
			strings.Join(users, ", "), more)
	}

	b.WriteString("\n")
}

// renderGrid writes the size × SIMD-level grid for one precision.
func renderGrid(b *bytes.Buffer, prec int) {
	cells := cellVerdicts(prec)

	keys := make([]gridKey, 0, len(cells))
	for k := range cells {
		keys = append(keys, k)
	}

	sort.Slice(keys, func(i, j int) bool {
		if keys[i].size != keys[j].size {
			return keys[i].size < keys[j].size
		}

		return keys[i].variant < keys[j].variant
	})

	b.WriteString("| Size | Algorithm |")

	for _, c := range simdColumns {
		fmt.Fprintf(b, " %s |", simdColumnNames[c])
	}

	b.WriteString("\n|---:|---|")

	for range simdColumns {
		b.WriteString(":---:|")
	}

	b.WriteString("\n")

	for _, k := range keys {
		fmt.Fprintf(b, "| %d | %s |", k.size, k.variant)

		for _, c := range simdColumns {
			mark := cellAbsent
			if v := cells[k][c]; v != "" {
				mark = v
			}

			fmt.Fprintf(b, " %s |", mark)
		}

		b.WriteString("\n")
	}

	b.WriteString(strings.TrimLeft(`
`+cellSelectable+` selectable — the highest-ranked codelet for its size within its own rank
tier, so `+"`registry.Lookup`"+` returns it on any host whose top supported tier is
that one.
`+cellCandidate+` registered candidate — outranked by a peer in the same tier, so the
compiled ranking never selects it. It is carried because the wisdom tuner can
still pick it on a host with different cache geometry (PLAN.md §2.2), and it
costs one arm of a wisdom measurement.
`+cellProbe+` probe-only — registered exclusively under `+"`-tags fftprobe`"+`; absent from
every production build. See the probe section for the verdict.
`+cellDisabled+` disabled — a row kept for the record at a negative priority. Never
selected, and not wisdom-reachable either.
`+cellAbsent+` no kernel at this size and tier.

Ranking is SIMD-level major and priority only orders within a level, so `+cellSelectable+`
appears once per (size, rank tier) and a cell can be selectable in the SSE2
column while an AVX2 cell one column over is selectable too — they win on
different hosts. `+"`RankLevel`"+` is taken into account: a demoted AVX2-encoded
codelet competes in the tier it was demoted into, not the one it executes in.

`, "\n"))
}

// renderCounts writes the per-target registration counts.
func renderCounts(b *bytes.Buffer) {
	b.WriteString("## Registration Counts\n\n")
	b.WriteString("| Target | Build constraint | complex64 | complex128 | Total |\n")
	b.WriteString("|---|---|---:|---:|---:|\n")

	total := 0

	for _, tgt := range targets {
		n64 := len(specsFor(tgt.kind, 64))
		n128 := len(specsFor(tgt.kind, 128))
		total += n64 + n128

		tag := tgt.buildTag
		if tag == "" {
			tag = "(all builds)"
		}

		fmt.Fprintf(b, "| %s | `%s` | %d | %d | %d |\n", tgt.kind, tag, n64, n128, n64+n128)
	}

	fmt.Fprintf(b, "\nTotal registered codelets: **%d**.\n\n", total)
}

// renderStaticSections describes kernel coverage that lives outside the
// codelet registry. Keep this in sync with internal/fft dispatch.
func renderStaticSections(b *bytes.Buffer) {
	b.WriteString(strings.TrimLeft(`
## Beyond the Codelet Registry

Codelets cover the tuned size-specific fast paths. Everything else is served
by these tiers, in dispatch order:

1. **Generic SIMD kernels** (internal/fft dispatch, internal/asm):
   size-generic DIT and Stockham kernels for AVX-512 / AVX2 / SSE3 / SSE2 on
   amd64, NEON on arm64, and SSE2/SSE3 on 386. These serve every power-of-two
   size without a registered codelet (on amd64 the AVX-512 tier also serves
   all Stockham-resolved sizes; see internal/fft/kernels_amd64_avx512.go).
2. **386 size-specific kernels** (internal/asm/x86, dispatched via
   internal/fft/kernels_386_asm.go): SSE2/SSE3 kernels for sizes 2/4/8/16,
   including the size-16 radix-16 variant.
3. **Pure-Go algorithm families** (internal/kernels, internal/transform):
   DIT, Stockham, mixed-radix 2/3/5/7/11, Bluestein (arbitrary lengths),
   six-step/eight-step (large sizes), and recursive decomposition — both
   precisions, every platform, and the only tier under -tags purego.

Higher plan-level features (real FFT, 2D/3D/N-D, batch/strided, convolution)
compose these 1D kernels; see README.md and PLAN.md.

## Testing

Every registered codelet is validated per-direction against the naive
reference DFT (internal/reference), plus round-trip and in-place coverage;
a meta-test asserts every signature has reference coverage
(internal/kernels/codelet_roundtrip_all_test.go). SIMD and pure-Go paths are
cross-checked in CI on amd64, 386, and arm64 (QEMU).
`, "\n"))
}
