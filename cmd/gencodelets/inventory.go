// renderInventory produces docs/IMPLEMENTATION_INVENTORY.md from the codelet
// spec table, so the inventory can never drift from the actual registrations.
// Non-codelet coverage (generic SIMD kernels, the 386 tier, the pure-Go
// algorithm families) is described in a static section below, maintained here
// alongside the dispatch code it describes.

// simdColumns is the column order of the quick-reference grids.
//
//nolint:gochecknoglobals // static configuration for the inventory renderer
var simdColumns = []string{"SIMDNone", "SIMDSSE2", "SIMDSSE3", "SIMDAVX2", "SIMDAVX512", "SIMDNEON"}

//nolint:gochecknoglobals // static configuration for the inventory renderer
var simdColumnNames = map[string]string{
	"SIMDNone":   "Go",
	"SIMDSSE2":   "SSE2",
	"SIMDSSE3":   "SSE3",
	"SIMDAVX2":   "AVX2",
	"SIMDAVX512": "AVX-512",
	"SIMDNEON":   "NEON",
}

